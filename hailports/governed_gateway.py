#!/usr/bin/env python3
"""Governed tool gateway — one choke point for bot/CLI tool calls.

Policy lives in data/runtime/gateway_policy.json. Hard rules apply to every
caller. Shadow mode (default) logs would-be denies without blocking. Enforce
mode turns on when data/flags/gateway_enforce exists.

Loopback HTTP door: POST /v1/tools/check (and /v1/tools/invoke as a check-only
alias) on the local-first gateway (:8790).
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
POLICY_PATH = Path(
    os.environ.get("GATEWAY_POLICY", str(ROOT / "data" / "runtime" / "gateway_policy.json"))
)
AUDIT_PATH = Path(
    os.environ.get("GATEWAY_AUDIT", str(ROOT / "data" / "runtime" / "gateway-audit.jsonl"))
)
ENFORCE_FLAG = Path(
    os.environ.get("GATEWAY_ENFORCE_FLAG", str(ROOT / "data" / "flags" / "gateway_enforce"))
)
ROLLUP_PATH = Path(
    os.environ.get(
        "GATEWAY_ROLLUP",
        os.environ.get("LOCAL_FIRST_ROLLUP", str(ROOT / "data" / "status" / "offload-today.md")),
    )
)

# Callers allowed to mutate CRM orgs. Prod still denied by default.
CRM_MUTATOR_CALLERS = {"crm-bot", "crm_bot"}

SEND_POST_ACTIONS = {
    "send",
    "post",
    "publish",
    "chatter",
    "chatter.post",
    "mail.send",
    "email.send",
    "outlook.send",
    "zoom.send",
    "chat.send",
    "imessage.send",
    "teams.send",
}

SEND_POST_TOOLS = {
    "mail.send",
    "email.send",
    "outlook.send",
    "zoom.send",
    "chat.send",
    "chatter.post",
    "chatter.create",
    "imessage.send",
    "teams.send",
    "slack.send",
}

CRM_MUTATE_TOOLS = {
    "crm.mutate",
    "crm.deploy",
    "crm.write",
    "crm.dml",
    "crm.apex",
}

CRM_TARGETS = {"crm", "crm-sandbox"}
CRM_PROD_TARGETS = {"crm-prod", "prod"}

# Employer / work surfaces where AI-fingerprint text is blocked.
EMPLOYER_SURFACES = {
    "employer",
    "work",
    "ado",
    "sharepoint",
    "outlook-work",
    "crm",
    "chatter",
}

AI_TELLS = [
    "as an ai",
    "as a language model",
    "i'm an ai",
    "i am an ai",
    "i'm just an assistant",
    "as your assistant",
    "i'd be happy to assist",
    "i'd be happy to help",
    "i've generated",
    "i have generated",
    "from claude",
    "claude here",
    "generated by",
    "language model",
    "as an artificial intelligence",
]

_QUERY_RULES: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"(?i)\b(?:seed|recovery)[\s-]+phrases?\b"), "seed_phrase"),
    (re.compile(r"(?i)\bprivate\s+keys?\b"), "private_key"),
    (
        re.compile(
            r"(?i)\b(?:passcodes?|passphrases?|credentials?)\b|"
            r"\bpasswords?\b(?!\s+(?:reset|recovery|polic(?:y|ies)|runbook|flow|template|"
            r"link|lifetime|lockout|expired?|expiry|change\s+flow))"
        ),
        "credentials",
    ),
    (re.compile(r"(?i)\b(?:2fa|mfa|otp)\b"), "otp"),
    (re.compile(r"(?i)\bverification[\s-]+codes?\b"), "otp"),
    (re.compile(r"(?i)\bone[\s-]*time[\s-]+(?:codes?|passwords?)\b"), "otp"),
    (re.compile(r"(?i)\btwo[\s-]*factor\b"), "otp"),
    (re.compile(r"(?i)\b(?:lawyers?|attorneys?)\b"), "legal_counsel"),
    (re.compile(r"(?i)\blegal\s+counsel\b"), "legal_counsel"),
    (re.compile(r"(?i)\b(?:legal|finance)\s+folders?\b"), "restricted_folder"),
    (re.compile(r"(?i)\baccountants?\b"), "accountant"),
    (re.compile(r"(?i)\bbank(?:ing)?\b|\bbank\s+statements?\b"), "bank"),
)

_SEGMENT = re.compile(
    r"(?i)\b(legal|law|litigation|contracts?|finance|financ\w*|accounting|"
    r"treasury|tax(?:es)?|payroll|bank(?:ing)?|compensation|salar\w*)\b"
)
_SEED_RE = re.compile(r"(?i)\b(?:seed|recovery)[\s-]+phrases?\b")
_OTP_RE = re.compile(
    r"(?i)(?:\b(?:2fa|mfa|otp)(?:\s+codes?)?\b|\b(?:verification|security)\s+codes?\b).{0,20}?\d{4,8}\b"
)
_PW_RE = re.compile(r"(?i)\b(?:password|passcode|pwd)\b\s*(?::|=|\bis\b)\s*(?!\[masked\])\S+")
_PRIVACY = re.compile(
    r"-----BEGIN [A-Z ]*PRIVATE KEY-----"
    r"|(?i:\b(?:token|api[_ -]?key|secret|client[_ -]?secret|access[_ -]?key|password)"
    r"\s*[:=]\s*['\"]?[A-Za-z0-9._~+/=-]{8,})"
)


def enforce_enabled(flag_path: Path | None = None) -> bool:
    path = flag_path or ENFORCE_FLAG
    return path.is_file()


def load_policy(path: Path | None = None) -> dict:
    p = path or POLICY_PATH
    if not p.is_file():
        return {"version": 1, "default": {}, "callers": {}}
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"version": 1, "default": {}, "callers": {}}
    return data if isinstance(data, dict) else {"version": 1, "default": {}, "callers": {}}


def _norm(value: str) -> str:
    return (value or "").strip().lower()


def _match_list(value: str, patterns: list[str] | None) -> bool:
    if not patterns:
        return False
    v = _norm(value)
    for pat in patterns:
        p = _norm(str(pat))
        if p == "*":
            return True
        if p.endswith(".*") and v.startswith(p[:-2]):
            return True
        if p.endswith("*") and v.startswith(p[:-1]):
            return True
        if v == p:
            return True
    return False


def hard_data_line(text: str = "", path: str = "", target: str = "") -> str | None:
    """Return a reason code when the hard data line is crossed."""
    blob = "\n".join(x for x in (text or "", path or "", target or "") if x)
    for pattern, reason in _QUERY_RULES:
        if pattern.search(blob):
            return f"hard_data_line:{reason}"
    if path:
        for segment in path.replace("\\", "/").split("/"):
            segment = segment.strip()
            if segment and _SEGMENT.search(segment):
                return "hard_data_line:restricted_path"
    if _SEED_RE.search(blob) or _OTP_RE.search(blob) or _PW_RE.search(blob) or _PRIVACY.search(blob):
        return "hard_data_line:secret"
    return None


def ai_fingerprint(text: str) -> str | None:
    low = (text or "").lower()
    for tell in AI_TELLS:
        if tell in low:
            return f"ai_fingerprint:{tell}"
    return None


def _is_send_post(tool: str, action: str) -> bool:
    t = _norm(tool)
    a = _norm(action)
    if t in SEND_POST_TOOLS or a in SEND_POST_ACTIONS:
        return True
    if t.endswith(".send") or t.endswith(".post") or t.endswith(".publish"):
        return True
    if a in {"send", "post", "publish"}:
        return True
    return False


def _is_crm_mutate(tool: str, action: str, target: str) -> bool:
    t = _norm(tool)
    a = _norm(action)
    tgt = _norm(target)
    if t in CRM_MUTATE_TOOLS:
        return True
    if a in {"mutate", "deploy", "write", "dml", "apex", "create", "update", "delete", "upsert"}:
        if tgt in CRM_TARGETS or tgt in CRM_PROD_TARGETS or tgt.startswith("crm"):
            return True
    if t.startswith("crm.") or t.startswith("crm."):
        if any(x in t for x in ("mutate", "deploy", "write", "dml", "apex", "create", "update", "delete")):
            return True
    return False


def _is_crm_prod(target: str, tool: str = "", action: str = "") -> bool:
    tgt = _norm(target)
    blob = " ".join((_norm(tool), _norm(action), tgt))
    if tgt in CRM_PROD_TARGETS:
        return True
    if "prod" in tgt.split("-") or tgt.endswith("_prod"):
        if tgt.startswith("crm") or "crm" in tgt:
            return True
    if re.search(r"(?i)\b(crm)[-_ ]?prod\b", blob):
        return True
    return False


def _is_employer_surface(target: str, surface: str = "") -> bool:
    for value in (_norm(target), _norm(surface)):
        if not value:
            continue
        if value in EMPLOYER_SURFACES:
            return True
        if value.startswith("employer") or value.startswith("employer"):
            return True
        # CRM / work targets with a suffix (crm-prod, outlook-work, ...)
        head = value.split("-", 1)[0].split("_", 1)[0]
        if head in EMPLOYER_SURFACES:
            return True
    return False


def evaluate(
    *,
    caller: str,
    tool: str,
    target: str = "",
    action: str = "",
    text: str = "",
    path: str = "",
    surface: str = "",
    policy: dict | None = None,
    enforce: bool | None = None,
) -> dict[str, Any]:
    """Decide allow/deny for one tool call. Never raises."""
    pol = policy if policy is not None else load_policy()
    mode = "enforce" if (enforce if enforce is not None else enforce_enabled()) else "shadow"
    caller_key = _norm(caller) or "unknown"
    tool_key = _norm(tool) or "unknown"
    target_key = _norm(target)
    action_key = _norm(action) or tool_key
    reasons: list[str] = []

    # 1) Hard data line
    hit = hard_data_line(text=text, path=path, target=target)
    if hit:
        reasons.append(hit)

    # 2) Draft-only outbound: deny send/post for mail/chat/chatter
    if _is_send_post(tool_key, action_key):
        reasons.append("draft_only:send_or_post")

    # 3) CRM mutations: only crm-bot; prod denied by default
    if _is_crm_mutate(tool_key, action_key, target_key):
        if caller_key not in CRM_MUTATOR_CALLERS:
            reasons.append("crm_mutate:caller_not_allowed")
        if _is_crm_prod(target_key, tool_key, action_key):
            reasons.append("crm_mutate:prod_denied")

    # 4) No AI-related text on employer / employer surfaces
    if _is_employer_surface(target_key, surface) or _norm(surface) in EMPLOYER_SURFACES:
        ai = ai_fingerprint(text)
        if ai:
            reasons.append(ai)

    # 5) Per-caller allow/deny lists
    default = pol.get("default") if isinstance(pol.get("default"), dict) else {}
    callers = pol.get("callers") if isinstance(pol.get("callers"), dict) else {}
    # Case-insensitive caller lookup
    entry = default
    for name, cfg in callers.items():
        if _norm(str(name)) == caller_key and isinstance(cfg, dict):
            entry = {**default, **cfg}
            break

    allow_tools = entry.get("allow_tools") if isinstance(entry.get("allow_tools"), list) else ["*"]
    deny_tools = entry.get("deny_tools") if isinstance(entry.get("deny_tools"), list) else []
    allow_targets = entry.get("allow_targets") if isinstance(entry.get("allow_targets"), list) else ["*"]
    deny_targets = entry.get("deny_targets") if isinstance(entry.get("deny_targets"), list) else []

    if deny_tools and _match_list(tool_key, [str(x) for x in deny_tools]):
        reasons.append("policy:deny_tool")
    elif allow_tools and not _match_list(tool_key, [str(x) for x in allow_tools]):
        reasons.append("policy:tool_not_allowed")

    if target_key:
        if deny_targets and _match_list(target_key, [str(x) for x in deny_targets]):
            reasons.append("policy:deny_target")
        elif allow_targets and not _match_list(target_key, [str(x) for x in allow_targets]):
            reasons.append("policy:target_not_allowed")

    would_deny = bool(reasons)
    if not would_deny:
        decision = "allow"
        allowed = True
    elif mode == "shadow":
        decision = "shadow_deny"
        allowed = True  # does not block
    else:
        decision = "deny"
        allowed = False

    return {
        "ok": True,
        "allowed": allowed,
        "decision": decision,
        "would_deny": would_deny,
        "reasons": reasons,
        "mode": mode,
        "caller": caller_key,
        "tool": tool_key,
        "target": target_key,
        "action": action_key,
        "ts": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def audit(result: dict, *, audit_path: Path | None = None, rollup_path: Path | None = None) -> None:
    """Append one audit row and refresh the gateway section of the daily rollup."""
    path = audit_path or AUDIT_PATH
    row = {
        "ts": result.get("ts") or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "caller": result.get("caller"),
        "tool": result.get("tool"),
        "target": result.get("target"),
        "action": result.get("action"),
        "decision": result.get("decision"),
        "allowed": result.get("allowed"),
        "would_deny": result.get("would_deny"),
        "reasons": result.get("reasons") or [],
        "mode": result.get("mode"),
    }
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, sort_keys=True) + "\n")
    except OSError:
        pass
    try:
        write_gateway_rollup(audit_path=path, rollup_path=rollup_path or ROLLUP_PATH)
    except Exception:
        pass


def check_call(payload: dict, *, policy: dict | None = None, enforce: bool | None = None, record: bool = True) -> dict:
    """Evaluate + optionally audit a tool-call payload."""
    args = payload.get("args") if isinstance(payload.get("args"), dict) else {}
    text = str(payload.get("text") or args.get("text") or args.get("body") or "")
    path = str(payload.get("path") or args.get("path") or "")
    result = evaluate(
        caller=str(payload.get("caller") or payload.get("bot") or "unknown"),
        tool=str(payload.get("tool") or payload.get("name") or "unknown"),
        target=str(payload.get("target") or payload.get("system") or ""),
        action=str(payload.get("action") or ""),
        text=text,
        path=path,
        surface=str(payload.get("surface") or ""),
        policy=policy,
        enforce=enforce,
    )
    if record and os.environ.get("GATEWAY_AUDIT_DISABLE") != "1":
        audit(result)
    return result


def write_gateway_rollup(audit_path: Path | None = None, rollup_path: Path | None = None) -> Path:
    """Append/replace a ## gateway section on the daily offload rollup."""
    apath = audit_path or AUDIT_PATH
    rpath = rollup_path or ROLLUP_PATH
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    allow_n = deny_n = shadow_n = 0
    if apath.is_file():
        try:
            for line in apath.read_text(encoding="utf-8", errors="replace").splitlines():
                if not line.strip():
                    continue
                try:
                    row = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if not str(row.get("ts") or "").startswith(today):
                    continue
                decision = str(row.get("decision") or "")
                if decision == "allow":
                    allow_n += 1
                elif decision == "deny":
                    deny_n += 1
                elif decision == "shadow_deny":
                    shadow_n += 1
        except OSError:
            pass
    section = (
        f"## gateway ({today} UTC)\n\n"
        f"- allowed: {allow_n}\n"
        f"- denied: {deny_n}\n"
        f"- shadow_deny: {shadow_n}\n"
        f"- mode: {'enforce' if enforce_enabled() else 'shadow'}\n"
    )
    try:
        rpath.parent.mkdir(parents=True, exist_ok=True)
        existing = ""
        if rpath.is_file():
            existing = rpath.read_text(encoding="utf-8", errors="replace")
        # Strip prior gateway section(s)
        parts = re.split(r"\n## gateway\b.*", existing, maxsplit=1, flags=re.S)
        head = parts[0].rstrip()
        body = (head + "\n\n" + section) if head else section
        rpath.write_text(body, encoding="utf-8")
    except OSError:
        pass
    return rpath


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] == "--selftest":
        return _selftest()
    if not argv or argv[0] in {"-h", "--help"}:
        sys.stdout.write(
            "usage: governed_gateway.py check --caller C --tool T [--target S] "
            "[--action A] [--text TXT] [--path P] [--json]\n"
        )
        return 0
    if argv[0] != "check":
        sys.stderr.write("unknown command\n")
        return 2
    caller = tool = target = action = text = path = ""
    as_json = False
    i = 1
    while i < len(argv):
        a = argv[i]
        if a == "--caller" and i + 1 < len(argv):
            caller = argv[i + 1]
            i += 2
        elif a == "--tool" and i + 1 < len(argv):
            tool = argv[i + 1]
            i += 2
        elif a == "--target" and i + 1 < len(argv):
            target = argv[i + 1]
            i += 2
        elif a == "--action" and i + 1 < len(argv):
            action = argv[i + 1]
            i += 2
        elif a == "--text" and i + 1 < len(argv):
            text = argv[i + 1]
            i += 2
        elif a == "--path" and i + 1 < len(argv):
            path = argv[i + 1]
            i += 2
        elif a == "--json":
            as_json = True
            i += 1
        else:
            i += 1
    result = check_call(
        {"caller": caller, "tool": tool, "target": target, "action": action, "text": text, "path": path}
    )
    if as_json:
        sys.stdout.write(json.dumps(result, indent=2) + "\n")
    else:
        sys.stdout.write(f"{result['decision']} allowed={result['allowed']} reasons={result['reasons']}\n")
    return 0 if result["allowed"] else 1


def _selftest() -> int:
    saved = os.environ.get("GATEWAY_AUDIT_DISABLE")
    os.environ["GATEWAY_AUDIT_DISABLE"] = "1"
    cases: list[tuple[str, bool]] = []

    def check(name: str, ok: bool) -> None:
        cases.append((name, ok))
        print(("ok " if ok else "FAIL ") + name)

    pol = {
        "version": 1,
        "default": {"allow_tools": ["*"], "deny_tools": [], "allow_targets": ["*"], "deny_targets": ["crm-prod"]},
        "callers": {
            "crm-bot": {"allow_tools": ["*"], "deny_tools": ["mail.send"]},
            "claude": {"deny_tools": ["crm.mutate"], "deny_targets": ["crm-prod"]},
        },
    }
    allow = evaluate(caller="claude", tool="notes.read", target="notes", policy=pol, enforce=False)
    check("allow read", allow["decision"] == "allow" and allow["allowed"] is True)

    send = evaluate(caller="claude", tool="outlook.send", action="send", policy=pol, enforce=False)
    check("shadow send", send["decision"] == "shadow_deny" and send["allowed"] is True)

    send_e = evaluate(caller="claude", tool="outlook.send", action="send", policy=pol, enforce=True)
    check("enforce send", send_e["decision"] == "deny" and send_e["allowed"] is False)

    secret = evaluate(
        caller="claude",
        tool="notes.read",
        text="password: hunter2",
        policy=pol,
        enforce=True,
    )
    check("secret blocked", secret["decision"] == "deny" and any("hard_data_line" in r for r in secret["reasons"]))

    legal = evaluate(
        caller="claude",
        tool="files.read",
        path="/docs/Legal/Finance/q3.pdf",
        policy=pol,
        enforce=True,
    )
    check("legal path blocked", legal["decision"] == "deny")

    crm_other = evaluate(
        caller="claude",
        tool="crm.mutate",
        target="crm-sandbox",
        action="mutate",
        policy=pol,
        enforce=True,
    )
    check("non-crm-bot crm denied", crm_other["decision"] == "deny")

    crm_bot = evaluate(
        caller="crm-bot",
        tool="crm.mutate",
        target="crm-sandbox",
        action="mutate",
        policy=pol,
        enforce=True,
    )
    check("crm-bot sandbox ok", crm_bot["decision"] == "allow")

    crm_prod = evaluate(
        caller="crm-bot",
        tool="crm.mutate",
        target="crm-prod",
        action="mutate",
        policy=pol,
        enforce=True,
    )
    check("prod denied", crm_prod["decision"] == "deny" and any("prod" in r for r in crm_prod["reasons"]))

    ai = evaluate(
        caller="claude",
        tool="outlook.draft",
        target="employer",
        surface="employer",
        text="As an AI, I can help with that.",
        policy=pol,
        enforce=True,
    )
    check("ai fingerprint blocked", ai["decision"] == "deny" and any("ai_fingerprint" in r for r in ai["reasons"]))

    if saved is None:
        os.environ.pop("GATEWAY_AUDIT_DISABLE", None)
    else:
        os.environ["GATEWAY_AUDIT_DISABLE"] = saved
    failed = [n for n, ok in cases if not ok]
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())

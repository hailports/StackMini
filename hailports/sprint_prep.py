def snapshot_outputs(directory: Path, payload: dict) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    day = payload["date"]
    json_path = directory / f"{day}.json"
    md_path = directory / f"{day}-top10.md"
    top = render_top10(
        payload["cards"], day=day, item_count=payload["item_count"],
        failures=len(payload.get("failures") or []),
    )
    atomic_text(json_path, json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    atomic_text(md_path, top)
    link_latest(directory, json_path.name)


def finish(directory: Path, *, day, iteration, items, result, wall_s, status, estimated) -> dict:
    payload = payload_for(day, iteration, items, result, status)
    top = render_top10(
        result["cards"], day=day, item_count=len(items), failures=len(result["failures"]),
    )
    meter = meter_row(
        ts=now_iso(), day=day, items=len(items), cards=len(result["cards"]),
        llm_calls=result["llm_calls"], prompt_tokens=result["prompt_tokens"],
        completion_tokens=result["completion_tokens"], wall_s=wall_s, status=status,
        tokens_estimated=estimated,
    )
    paths = write_outputs(directory, payload, top, meter)
    paths["status"] = status
    paths["item_count"] = len(items)
    paths["meter_row"] = meter
    return paths


def prior_from_snapshot(payload) -> tuple[dict, int, int, int]:
    """Cards from an unfinished run. A finished day file starts over."""
    if not isinstance(payload, dict) or payload.get("status") != "running":
        return {}, 0, 0, 0
    prior = {}
    for card in payload.get("cards") or []:
        if isinstance(card, dict) and card.get("what_it_is") and not card.get("skipped"):
            prior[str(card.get("id") or "")] = card
    return (
        prior,
        int(payload.get("prompt_tokens") or 0),
        int(payload.get("completion_tokens") or 0),
        int(payload.get("llm_calls") or 0),
    )


def execute(stack: Path, *, iteration: str, limit: int = 0, checker=None) -> dict:
    t0 = time.monotonic()
    day = today()
    out = stack / "data" / "ado_prep"
    log_path = out / "run.log"
    if (stack / "data" / "flags" / "ado_prep_off").exists():
        log_line(log_path, "off")
        return {"status": "off"}
    if not iteration:
        log_line(log_path, "iteration_unset")
        return {"status": "iteration_unset"}
    os.environ.setdefault("ADO_FORCE_MINI", "1")
    os.environ.setdefault("CHATPRIO_ROLE", "background")
    root = str(stack)
    if root not in sys.path:
        sys.path.insert(0, root)
    from tools import ado_client
    checker = checker or real_board_gate
    project = ado_client.PROJECT
    try:
        bridge_cm = ado_client.AdoBridge()
        bridge = bridge_cm.connect()
    except Exception as exc:
        if is_sso_remint(exc):
            log_line(log_path, "sso_remint")
            return {"status": "sso_remint"}
        log_line(log_path, "bridge " + mask_secrets(str(exc))[:160])
        return {"status": "bridge_error"}
    try:
        ids = fetch_open_ids(bridge, project, iteration)
        if limit:
            ids = ids[:limit]
        log_line(log_path, "items %d" % len(ids))
        items = load_items(ado_client, bridge, ids)
    except SsoRemint:
        log_line(log_path, "sso_remint")
        try:
            bridge.close()
        except Exception:
            pass
        return {"status": "sso_remint"}
    except Exception as exc:
        log_line(log_path, "fetch " + mask_secrets(str(exc))[:160])
        try:
            bridge.close()
        except Exception:
            pass
        return {"status": "fetch_error"}
    try:
        bridge.close()
    except Exception:
        pass
    audit = audit_index(load_audit_text(stack))
    digests = load_digest_texts(stack)
    model = live_model(stack, log_path)
    result = {"cards": [], "failures": [], "prompt_tokens": 0, "completion_tokens": 0, "llm_calls": 0}
    status = "ok"
    turn = wait_turn(stack, 120)
    log_line(log_path, "slot " + turn)
    if turn == "down":
        for item in items:
            result["cards"].append(blank_card(item, skipped="model_down"))
            result["failures"].append({"id": str(item.get("id") or ""), "error": "model_down"})
        return finish(
            out, day=day, iteration=iteration, items=items, result=result,
            wall_s=time.monotonic() - t0, status="model_down", estimated=False,
        )

    brain_cache = {}

    def cached_search(title: str) -> str:
        key = clip(title, 180)
        if key not in brain_cache:
            brain_cache[key] = search_work_brain(key)
        return brain_cache[key]

    def take(item, ordinal: int, label: str):
        one = run_items(
            [item], model=model, search=cached_search, audit=audit,
            digests=digests, checker=checker,
        )
        result["prompt_tokens"] += one["prompt_tokens"]
        result["completion_tokens"] += one["completion_tokens"]
        result["llm_calls"] += one["llm_calls"]
        skipped = (one["cards"][0].get("skipped") if one["cards"] else "") or "ok"
        log_line(log_path, "%s %d/%d %s %s" % (label, ordinal, len(items), item.get("id"), skipped))
        return one, skipped

    prior = {}
    prior_path = out / f"{day}.json"
    if prior_path.is_file():
        try:
            old = json.loads(prior_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            old = {}
        prior, p_tok, c_tok, calls = prior_from_snapshot(old)
        result["prompt_tokens"] = p_tok
        result["completion_tokens"] = c_tok
        result["llm_calls"] = calls
    if prior:
        log_line(log_path, "resume %d" % len(prior))
    retry = []
    for index, item in enumerate(items, 1):
        if str(item.get("id") or "") in prior:
            result["cards"].append(prior[str(item.get("id"))])
            continue
        log_line(log_path, "start %s/%s %s" % (index, len(items), item.get("id")))
        one, skipped = take(item, index, "item")
        if skipped == "yielded":
            retry.append(item)
            continue
        result["cards"].extend(one["cards"])
        result["failures"].extend(one["failures"])
        snapshot_outputs(out, payload_for(day, iteration, items, result, "running"))
        if skipped == "model_down":
            status = "model_down"
            for rest in items[index:]:
                result["cards"].append(blank_card(rest, skipped="not_run"))
                result["failures"].append({"id": str(rest.get("id") or ""), "error": "not_run"})
            break
    if status != "model_down":
        for index, item in enumerate(retry, 1):
            one, skipped = take(item, index, "retry")
            result["cards"].extend(one["cards"])
            result["failures"].extend(one["failures"])
            snapshot_outputs(out, payload_for(day, iteration, items, result, "running"))
            if skipped == "model_down":
                status = "model_down"
                break
    wall = time.monotonic() - t0
    return finish(
        out, day=day, iteration=iteration, items=items, result=result,
        wall_s=wall, status=status, estimated=bool(model.estimated["yes"]),
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Read-only local sprint prep")
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--iteration", default=DEFAULT_ITERATION)
    parser.add_argument("--stack", default="")
    args = parser.parse_args(argv)
    stack = Path(args.stack) if args.stack else stack_home()
    if args.stack:
        os.environ["ADO_PREP_STACK"] = args.stack
    out = stack / "data" / "ado_prep"
    lock = try_lock(out / "run.lock")
    if lock is None:
        log_line(out / "run.log", "already_running")
        print("already_running")
        return 0
    try:
        result = execute(stack, iteration=args.iteration, limit=args.limit)
    finally:
        lock.close()
    status = result.get("status") or "ok"
    if status == "sso_remint":
        print("sso_remint")
        return 0
    row = result.get("meter_row") or {}
    print("status=%s items=%s llm_calls=%s prompt_tokens=%s completion_tokens=%s avoided=%s wall_s=%s" % (
        status, result.get("item_count"), row.get("llm_calls"), row.get("prompt_tokens"),
        row.get("completion_tokens"), row.get("grok_bot_tokens_avoided"), row.get("wall_s"),
    ))
    return 0 if status in {"ok", "off", "model_down", "iteration_unset"} else 1


if __name__ == "__main__":
    sys.exit(main())

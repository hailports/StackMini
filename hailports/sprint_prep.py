def read_api(bridge, method: str, path: str, body=None):
    """Allow listed reads. Refuse every other tracker call."""
    verb = (method or "").upper()
    if verb == "GET":
        return bridge.api(verb, path, body=body)
    if verb == "POST" and ("/wiql" in path or path.endswith("wiql") or "workitemsbatch" in path):
        return bridge.api(verb, path, body=body)
    raise RuntimeError("read-only prep refuses " + verb)


def last_comments(rows, n: int = 3) -> list[dict]:
    cleaned = []
    for row in rows or []:
        if not isinstance(row, dict):
            continue
        cleaned.append({
            "who": display_name(row.get("createdBy") or row.get("created_by")),
            "when": str(row.get("createdDate") or row.get("modifiedDate") or ""),
            "text": html_to_text(row.get("text") or row.get("renderedText") or ""),
        })
    cleaned.sort(key=lambda c: c["when"], reverse=True)
    return cleaned[:n]



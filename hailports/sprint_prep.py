"""Read-only sprint prep cards from the local model.

The tracker is read. Nothing is posted, nothing is sent, and a suggested
state stays a suggestion. Ticket text is wrapped as data. A draft note is
kept only when the comment gate accepts it.

Set ADO_PREP_ITERATION to the iteration path. Set ADO_PREP_STACK to the
stack root if it is not ~/claude-stack. Weekday runs belong in a scheduler
with one lock so two runs cannot overlap.
"""
